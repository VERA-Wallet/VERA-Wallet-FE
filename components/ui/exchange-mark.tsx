/**
 * 24×24로 그려진 마크를 32×32 배지 안에 여백을 두고 앉힌다.
 * 32/24 × 0.82 = 1.0933, 남는 여백을 반으로 나눠 2.88씩 민다 — 중심 12가 정확히 16으로 간다.
 */
const GLYPH_TRANSFORM = "translate(2.88 2.88) scale(1.0933)";

export function ExchangeMark({ exchange, size = 32 }: { exchange: ExchangeDefinition; size?: number }) {
  const mark = EXCHANGE_MARK[exchange.id] ?? null;

  return (
    <svg
      aria-hidden="true"
      data-exchange-mark={exchange.id}
      className="shrink-0"
      width={size}
      height={size}
      viewBox="0 0 32 32"
    >
      <rect width="32" height="32" rx="10" fill={mark?.color ?? exchange.color} />
      {mark === null ? (
        <text x="16" y="21" textAnchor="middle" fontSize="12" fontWeight="700" fill="#ffffff">
          {exchange.initials}
        </text>
      ) : (
        <g transform={GLYPH_TRANSFORM}>{mark.glyph}</g>
      )}
    </svg>
  );
}
